def test_sdf_and_rdkit_molecule(tmp_path):
    chem = pytest.importorskip("rdkit.Chem")
    from rdkit.Chem import AllChem

    mol = chem.AddHs(chem.MolFromSmiles("CO"))
    AllChem.EmbedMultipleConfs(mol, numConfs=3, randomSeed=1)
    path = tmp_path / "c.sdf"
    writer = chem.SDWriter(str(path))
    for k, conf in enumerate(mol.GetConformers()):
        mol.SetProp("MMFF_Energy", str(1.0 + k))
        writer.write(mol, confId=conf.GetId())
    writer.close()
    top, src = formats.open_trajectory(str(path))
    assert src.n_frames == 3
    assert top.n_atoms == mol.GetNumAtoms()
    assert [src.energy(i) for i in range(3)] == [1.0, 2.0, 3.0]

    lattice = {"lattice": [[9, 0, 0], [0, 9, 0], [0, 0, 9]]}
    mol.SetProp(formats.CELL_PROPERTY, json.dumps(lattice))
    top, src = formats.from_rdkit(mol)
    assert src.n_frames == 3
    assert np.allclose(src.default_box, np.eye(3) * 9)
    with pytest.raises(formats.FormatError):
        formats.from_rdkit(chem.MolFromSmiles("C"))
