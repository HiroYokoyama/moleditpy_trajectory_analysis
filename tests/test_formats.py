def test_xyz_energies_and_lattice(tmp_path):
    frames = np.zeros((3, 2, 3))
    frames[:, 1, 0] = [1.0, 1.1, 1.2]
    comments = [
        'Lattice="10 0 0 0 10 0 0 0 10" Properties=species:S:1:pos:R:3 energy=-1.5',
        "Coordinates from ORCA-job x E -76.25",
        "  -12.345678",
    ]
    path = tmp_path / "t.xyz"
    write_xyz(path, ["O", "H"], frames, comments)
    top, src = formats.open_trajectory(str(path))
    try:
        assert top.symbols == ["O", "H"]
        assert src.n_frames == 3
        assert [src.energy(i) for i in range(3)] == [-1.5, -76.25, -12.345678]
        assert np.allclose(src.read_frame(0)[1], np.eye(3) * 10)
        assert np.allclose(src.read_frame(2)[0][1], [1.2, 0, 0])
    finally:
        src.close()


def test_xyz_ignores_incomplete_last_frame(tmp_path):
    path = tmp_path / "t.xyz"
    write_xyz(path, ["C"], np.zeros((2, 1, 3)))
    with open(path, "a", encoding="ascii") as fh:
        fh.write("1\npartial\n")
    _, src = formats.open_trajectory(str(path))
    try:
        assert src.n_frames == 2
    finally:
        src.close()


def test_pdb_models_cryst_and_remarks(tmp_path):
    frames = np.array([[[1.0, 1.0, 1.0], [2.0, 2.0, 2.0]]] * 3)
    frames[2, 0, 0] = 3.0
    path = tmp_path / "t.pdb"
    write_pdb(
        path,
        frames,
        cryst=(15, 15, 15, 90, 90, 90),
        remarks=["ENERGY = -10.0", "ENERGY = -11.0", "ENERGY = -9.5"],
    )
    top, src = formats.open_trajectory(str(path))
    try:
        assert src.n_frames == 3
        assert top.symbols == ["C", "C"]
        assert top.resnames == ["LIG", "LIG"]
        assert np.allclose(src.read_frame(2)[0][0], [3.0, 1.0, 1.0])
        assert np.allclose(src.read_frame(1)[1], np.eye(3) * 15, atol=1e-6)
        assert [src.energy(i) for i in range(3)] == [-10.0, -11.0, -9.5]
    finally:
        src.close()


def test_parse_energy_variants():
    assert formats.parse_energy("energy: -5.07 gnorm: 0.01") == -5.07
    assert formats.parse_energy("E=-3.0") == -3.0
    assert formats.parse_energy("Etot = 1.5e-1") == pytest.approx(0.15)
    assert formats.parse_energy("frame 3") is None
    # Bare integers are counters, not energies.
    assert formats.parse_energy("42") is None
    assert formats.parse_time("Generated by trjconv : t= 10.000 step= 5000") == 10.0


def test_cell_property_and_parameters():
    text = json.dumps(
        {
            "lattice": [[10, 0, 0], [0, 11, 0], [0, 0, 12]],
            "origin": [0, 0, 0],
            "pbc": [True, True, True],
        }
    )
    assert np.allclose(formats.cell_from_property(text), np.diag([10, 11, 12]))
    assert formats.cell_from_property("not json") is None
    assert formats.cell_from_property(json.dumps({"lattice": [[0] * 3] * 3})) is None
    cell = formats.cell_from_parameters(10, 10, 10, 90, 90, 60)
    assert np.allclose(np.linalg.norm(cell, axis=1), [10, 10, 10])


